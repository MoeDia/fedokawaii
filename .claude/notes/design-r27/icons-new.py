# ── the volume's ladder (18 × 12: the speaker and up to three arcs, all centred on row 6) ────
DOT = {5: [7], 6: [7], 7: [7]}
ARC_A = {4: [9], 5: [10], 6: [10], 7: [10], 8: [9]}
ARC_B = {2: [11], 3: [12], 4: [13], 5: [13], 6: [13], 7: [13], 8: [13], 9: [12], 10: [11]}
ARC_C = {1: [14], 2: [15], 3: [16], 4: [16], 5: [17], 6: [17], 7: [17], 8: [16], 9: [16], 10: [15], 11: [14]}
def vol(*parts):
    rows = [list("." * 18) for _ in range(12)]
    for y, r in enumerate(SPK, 1):
        for x, v in enumerate(r):
            if v == "#": rows[y][x] = "#"
    for p in parts:
        for y, xs in p.items():
            for x in xs: rows[y][x] = "#"
    return "\n" + "\n".join("".join(r) for r in rows)
ICONS["vol-0"] = vol()
