def slashed(art, gap=True):
    """ART with a slash from its top left to its bottom right, a pixel of paper either side of it"""
    rows = [list(r) for r in art.strip("\n").split("\n")]
    h, w = len(rows), len(rows[0])
    line = {(y, y) for y in range(min(h, w))}                 # (row, col)
    near = {(y + dy, x + dx) for y, x in line for dy in (-1, 0, 1) for dx in (-1, 0, 1)} - line
    for y in range(h):
        for x in range(w):
            if (y, x) in line: rows[y][x] = "#"
            elif gap and (y, x) in near and abs((x - y)) == 1: rows[y][x] = "."
    return "\n" + "\n".join("".join(r) for r in rows)
