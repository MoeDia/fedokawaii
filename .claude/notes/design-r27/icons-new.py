# ── brightness: a ring half lit (◐), a pair of dots round it for each level ───────────────
def bri(n):
    dots = [((0, 5), (0, 6)), ((11, 5), (11, 6)), ((5, 0), (6, 0)), ((5, 11), (6, 11)),
            ((1, 1), (1, 10)), ((10, 1), (10, 10)), ((1, 10), (10, 1)), ((1, 1), (10, 10))]
    order = [(0, 1), (2, 3), (4, 5), (6, 7)][:n]
    g = [list(r) for r in [
        "............",
        "............",
        "....####....",
        "...#..###...",
        "..#...####..",
        "..#...####..",
        "..#...####..",
        "..#...####..",
        "...#..###...",
        "....####....",
        "............",
        "............"]]
    pts = set()
    for a, b in order:
        for p in dots[a] + dots[b]:
            pts.add(p)
    for y, x in pts: g[y][x] = "#"
    return "\n" + "\n".join("".join(r) for r in g)
for n in range(5):
    ICONS[f"bri-{n}"] = bri(n)

