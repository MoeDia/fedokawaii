# brightness, again: a bulb — a pair of rays for each level (bri-0: none)
def bulb(n):
    g = [list(r) for r in [
        "............",
        "....####....",
        "...#....#...",
        "..#......#..",
        "..#......#..",
        "..#......#..",
        "...#....#...",
        "....#..#....",
        "....####....",
        "....####....",
        ".....##.....",
        "............"]]
    rays = [[(4, 0), (4, 11)], [(1, 1), (1, 10)], [(7, 0), (7, 11)], [(0, 2), (0, 9)]]
    for pair in rays[:n]:
        for y, x in pair: g[y][x] = "#"
    if n >= 3:                                    # (the brightest: the bulb's glass lit too)
        for y, x in ((3, 5), (3, 6), (4, 4), (4, 5), (4, 6), (4, 7), (5, 5), (5, 6)): g[y][x] = "#"
    return "\n" + "\n".join("".join(r) for r in g)
for n in range(5):
    ICONS[f"bri-{n}"] = bulb(n)
