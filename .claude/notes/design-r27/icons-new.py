def spk(extra):
    """the speaker on rows 1–11 (its middle on row 6), and EXTRA (row → {col}) to its right"""
    rows = ["............"] + [r for r in SPK]
    out = []
    for y, r in enumerate(rows):
        r = list(r)
        for x in extra.get(y, ()):
            r[x] = "#"
        out.append("".join(r))
    return "\n" + "\n".join(out)
