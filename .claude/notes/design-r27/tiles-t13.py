def grid(s):
    rows = [r for r in s.strip("\n").split("\n")]
    n = len(rows)
    assert n in (12, 14) and all(len(r) == n for r in rows), [len(r) for r in rows]
    return rows


if __name__ == "__main__":
    from PIL import Image, ImageDraw
    T.update({"icon-" + k: v for k, v in I12.items()})
    names = list(T)
    inks = [((0x18, 0x17, 0x15), (0xd4, 0xbf, 0x9a)), ((0xe8, 0xe3, 0xc2), (0x12, 0x26, 0x25))]
    S, cellw = 8, 14 * 8 + 24
    W, H = len(names) * cellw + 10, 2 * (14 * 8 + 40) + 2 * 40
    im = Image.new("RGB", (W, H), (60, 60, 60)); d = ImageDraw.Draw(im)
    for k, n in enumerate(names):
        g = grid(T[n])
        for band, (bg, fg) in enumerate(inks):
            ox, oy = 10 + k * cellw, 10 + band * (14 * 8 + 60)
            d.rectangle([ox - 4, oy - 4, ox + 14 * S + 3, oy + 14 * S + 3], fill=bg)
            for y, row in enumerate(g):
                for x, c in enumerate(row):
                    if c == "#" and True:
                        d.rectangle([ox + x * S, oy + y * S, ox + x * S + S - 1, oy + y * S + S - 1], fill=fg)
            # 1× beside it, below
            for y, row in enumerate(g):
                for x, c in enumerate(row):
                    im.putpixel((ox + x, oy + 14 * S + 8 + y), fg if c == "#" else bg)
        d.text((10 + k * cellw, H - 30), n[5:], fill=(255, 255, 255))
    im.save(sys.argv[1]); print(im.size)
