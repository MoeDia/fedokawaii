def bits(s):
    rows = [r for r in s.strip("\n").split("\n")]
    assert len(rows) == 10 and all(len(r) == 10 for r in rows), rows
    return rows
red = {"dark": (0xeb, 0x53, 0x24), "light": (0xa8, 0x42, 0x22)}
paper = {"dark": (0x25, 0x20, 0x1a), "light": (0xf9, 0xf5, 0xde)}
text = {"dark": (0xd4, 0xbf, 0x9a), "light": (0x12, 0x26, 0x25)}
black = (0x11, 0x13, 0x14)
S = 8
W, H = 9 * 24 + 8, 2 * (24 + 24) + 8
out = Image.new("RGB", (W * S, H * S), (60, 60, 60))
def put(img, x, y, c):
    for i in range(S):
        for j in range(S):
            img.putpixel((x * S + i, y * S + j), c)
worst = 99
for ti, th in enumerate(("dark", "light")):
    oy = 4 + ti * 48
    for k in range(1, 10):
        ox = 4 + (k - 1) * 24
        for y in range(20):
            for x in range(22):
                put(out, ox + x, oy + y, paper[th]); put(out, ox + x, oy + 24 + y, paper[th])
        # the seal 16 across centred in a 22 x 20 paper box: centre (11, 10)
        cx, cy = 11, 10
        circ = set()
        for y in range(20):
            for x in range(22):
                if ((x + 0.5 - cx) / 8) ** 2 + ((y + 0.5 - cy) / 8) ** 2 <= 1.0:
                    put(out, ox + x, oy + y, red[th]); circ.add((x, y))
        r = bits(N[k])
        for y in range(10):
            for x in range(10):
                if r[y][x] == "#":
                    px, py = x + 6, y + 5
                    put(out, ox + px, oy + py, black)
                    put(out, ox + px, oy + 24 + py, text[th])
                    # the ink's distance to the circle's outside: every neighbour within 1 px inside
                    for dx in (-1, 0, 1):
                        for dy in (-1, 0, 1):
                            if (px + dx, py + dy) not in circ:
                                worst = min(worst, 0); print("touches:", k, x, y)
out.save(sys.argv[1])
