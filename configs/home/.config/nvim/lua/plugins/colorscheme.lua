-- ~/.config/nvim/lua/plugins/colorscheme.lua — added on top of the LazyVim starter.
-- gruvbox.nvim with its palette remapped to the desktop's colours: on the dark theme ink
-- ground and paper text (gruvbox's dark/bright colours), on the light theme paper ground
-- and ink text (its light/faded colours). The ground itself is left to the terminal
-- (transparent_mode): the see-through one every text screen has, the wallpaper faintly behind.
-- No italics: Sumi Term has one upright face, and a slanted copy of a dot font smears.
-- 'background' is never set here: Neovim asks foot
-- which ground it has, and foot tells it again when kawa-theme switches (DEC mode 2031),
-- so open editors follow the desktop. Generated by tools/build-themes.py; edit the palette there.
return {
  {
    "ellisonleao/gruvbox.nvim",
    priority = 1000,
    -- the line under the cursor: a shade of the ground that shows (gruvbox would take the
    -- light theme's text colour for it on paper — far too heavy there)
    init = function()
      -- the palette for the ground Neovim has: gruvbox reads it each time it loads — at the
      -- start, and again whenever foot tells Neovim the ground changed
      local dark = {
        dark0_hard = "#181715", dark0 = "#181715", dark0_soft = "#1c1916",
        dark1 = "#1c1916", dark2 = "#221e1a", dark3 = "#2d251e", dark4 = "#3c2f22",
        gray = "#8a7755",
        light0_hard = "#e8e3c2", light0 = "#f5ecc2", light1 = "#e7cfa1", light2 = "#c3ab88",
        light3 = "#ac9162", light4 = "#cab596",
        bright_red = "#eb5324", bright_green = "#96d1aa", bright_yellow = "#fbe6a0",
        bright_blue = "#a7d4e4", bright_purple = "#b5b1d8", bright_aqua = "#82c1b4",
        bright_orange = "#f68c50",
        neutral_red = "#eb5324", neutral_yellow = "#e2b540",
        -- the light theme's accents, deepened to read on paper
        faded_red = "#a84222", faded_green = "#437742", faded_yellow = "#986f2d",
        faded_blue = "#006eb8", faded_purple = "#66629c", faded_aqua = "#00726a",
        faded_orange = "#bb542d",
      }
      local light = vim.tbl_extend("force", dark, {
        light0_hard = "#e8e3c2", light0 = "#e8e3c2", light0_soft = "#f7f1d1",
        light1 = "#ecdfb3", light2 = "#dfcc9c", light3 = "#d7bc8c", light4 = "#8b917f",
        dark0_hard = "#121b1b", dark0 = "#121b1b", dark1 = "#122625", dark2 = "#122625",
        dark3 = "#586459", dark4 = "#586459", gray = "#586459",
        faded_red = "#a84222", faded_green = "#437742", faded_yellow = "#986f2d",
        faded_blue = "#006eb8", faded_purple = "#66629c", faded_aqua = "#00726a",
        faded_orange = "#bb542d",
      })
      vim.api.nvim_create_autocmd("ColorSchemePre", {
        group = vim.api.nvim_create_augroup("kawa_ground", { clear = true }),
        pattern = "gruvbox",
        callback = function()
          local ok, g = pcall(require, "gruvbox")
          if ok then g.config.palette_overrides = vim.o.background == "light" and light or dark end
        end,
      })
      vim.api.nvim_create_autocmd("ColorScheme", {
        group = vim.api.nvim_create_augroup("kawa_cursorline", { clear = true }),
        pattern = "gruvbox",
        callback = function()
          local bg = vim.o.background == "light" and "#ecdfb3" or "#2d251e"
          vim.api.nvim_set_hl(0, "CursorLine", { bg = bg })
          -- the picker's counts ("12/403"): in the comments' quiet ink, not the faint one
          -- gruvbox gives them (close to the ground itself)
          vim.api.nvim_set_hl(0, "SnacksPickerTotals", { link = "Comment" })
          -- what is selected (the completion menu's row, the wild menu's): the desktop's lacquer
          -- with the strongest cream on it, as every menu has it (gruvbox's blue held 3.3 : 1 on paper)
          local sel = vim.o.background == "light"
            and { bg = "#82241f", fg = "#f8f3d8" }
            or { bg = "#82241f", fg = "#f5ecc2" }
          vim.api.nvim_set_hl(0, "PmenuSel", sel)
          vim.api.nvim_set_hl(0, "WildMenu", sel)
          -- the first screen (look.lua) as a text screen: the heading's icon vermilion, its
          -- name in the text's ink, the stitch in edge2; the rows' glyphs vermilion, their
          -- names the text, their keys and the start's time muted
          local t = vim.o.background == "light"
            and { icon = "#a84222", text = "#122625", stitch = "#d7bc8c", muted = "#586459" }
            or { icon = "#f47b58", text = "#e7cfa1", stitch = "#3c2f22", muted = "#cab596" }
          vim.api.nvim_set_hl(0, "KawaIcon", { fg = t.icon })
          vim.api.nvim_set_hl(0, "KawaName", { fg = t.text })
          vim.api.nvim_set_hl(0, "KawaStitch", { fg = t.stitch })
          vim.api.nvim_set_hl(0, "SnacksDashboardIcon", { fg = t.icon })
          vim.api.nvim_set_hl(0, "SnacksDashboardDesc", { fg = t.text })
          vim.api.nvim_set_hl(0, "SnacksDashboardKey", { fg = t.muted })
          vim.api.nvim_set_hl(0, "SnacksDashboardFooter", { fg = t.muted })
          vim.api.nvim_set_hl(0, "SnacksDashboardSpecial", { fg = t.muted })
          -- diagnostics in the design's inks (docs/design-system.md §1): the sign and the code's
          -- underline in the severity's ink — an error vermilion (accent_text), a warning yellow, a
          -- note asagi, a hint muted; the message's words muted at the line's end, the words' own
          -- ink in the float (vermilion marks, never carries a sentence: no red on sumi reads).
          -- The base Diagnostic* groups keep the severity's ink on purpose: only what links to
          -- them (lualine's counts, Trouble's and Telescope's marks — short marks) draws with them
          local d = vim.o.background == "light"
            and { Error = "#a84222", Warn = "#986f2d", Info = "#00726a", Hint = "#586459" }
            or { Error = "#f47b58", Warn = "#e2b540", Info = "#82c1b4", Hint = "#cab596" }
          for k, c in pairs(d) do
            vim.api.nvim_set_hl(0, "Diagnostic" .. k, { fg = c })
            vim.api.nvim_set_hl(0, "DiagnosticSign" .. k, { fg = c })
            vim.api.nvim_set_hl(0, "DiagnosticVirtualText" .. k, { fg = t.muted })
            vim.api.nvim_set_hl(0, "DiagnosticVirtualLines" .. k, { fg = t.muted })
            vim.api.nvim_set_hl(0, "DiagnosticFloating" .. k, { fg = t.text })
            vim.api.nvim_set_hl(0, "DiagnosticUnderline" .. k, { sp = c, underline = true })
          end
          -- the status line (lua/config/statusline.lua): a tile in the mode's ink, the branch and
          -- the place on the key's ground, the words between in the muted ink on the line's own
          local p = ({
            dark = { ground = "#181715", line = "#221e1a", key = "#221e1a", text = "#e7cfa1", muted = "#cab596", accent = "#eb5324", teal = "#82c1b4", yellow = "#e2b540", blue = "#a7d4e4", red = "#eb5324", on_accent = "#111314" },
            light = { ground = "#e8e3c2", line = "#dfcc9c", key = "#f8f3d8", text = "#122625", muted = "#586459", accent = "#a84222", teal = "#00726a", yellow = "#986f2d", blue = "#006eb8", red = "#a84222", on_accent = "#f8f3d8" },
          })[vim.o.background == "light" and "light" or "dark"]
          local function set(name, spec) vim.api.nvim_set_hl(0, "KawaSt" .. name, spec) end
          local function tile(name, ink)
            set(name, { bg = ink, fg = ink == p.accent and p.on_accent or p.ground, bold = true })
          end
          tile("Normal", p.accent); tile("Insert", p.teal); tile("Visual", p.yellow)
          tile("Replace", p.red); tile("Command", p.blue); tile("Terminal", p.teal)
          vim.api.nvim_set_hl(0, "StatusLine", { bg = p.line, fg = p.muted })
          vim.api.nvim_set_hl(0, "StatusLineNC", { bg = p.line, fg = p.muted })
          set("Key", { bg = p.key, fg = p.text })
          set("Quiet", { bg = p.line, fg = p.muted })
          set("File", { bg = p.line, fg = p.muted })
          set("Changed", { bg = p.line, fg = p.yellow, bold = true })
          set("Root", { bg = p.line, fg = p.teal })
          set("Recording", { bg = p.line, fg = p.accent, bold = true })
          set("Debug", { bg = p.line, fg = p.yellow })
          set("Added", { bg = p.line, fg = p.teal })
          set("Modified", { bg = p.line, fg = p.yellow })
          set("Removed", { bg = p.line, fg = p.accent })
          for k, c in pairs(d) do set(k, { bg = p.line, fg = c }) end
        end,
      })
    end,
    opts = {
      contrast = "hard",
      transparent_mode = true,
      italic = { strings = false, emphasis = false, comments = false, operators = false, folds = false },
    },
  },
  { "LazyVim/LazyVim", opts = { colorscheme = "gruvbox" } },
}
