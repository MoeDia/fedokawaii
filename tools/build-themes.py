def gtk3_theme(m, p):
    # A GTK 3 theme of its own per mode — adw-gtk3 with the palette — rather than colours
    # in ~/.config/gtk-3.0/gtk.css: GTK 3 reads that file once per process, but reloads a
    # theme live when the theme's name changes. So kawa-theme switching Fedokawaii ⇄
    # Fedokawaii-dark recolours every open GTK 3 window, the portal's file dialog included.
    path = f"~/.local/share/themes/{p['gtk']}/gtk-3.0/gtk.css"
    out = [f"/* {header(path, NAMES[m] + ' for GTK 3: ' + p['base'] + ' with the desktop palette')}",
           "   (the redefined colours after the import replace adw-gtk3's own) */",
           f'@import url("file:///usr/share/themes/{p["base"]}/gtk-3.0/gtk.css");']
    out += [f"@define-color {k:<26}#{v};" for k, v in gtk_vars(m, p)]
    out += ["",
            "/* Brave (Chromium's GTK mode, theme.sh sets it) samples these same colours for its tab",
            "   strip, toolbar and menus (its address bar keeps Brave's own). Chromium gives every",
            "   style node it reads the class .chromium, so the rules below reach Brave only: its",
            "   accent (checked boxes, the selected row) is the vermilion rather than a dull blend,",
            "   its tooltips are the palette's, and its tab strip stays the same when the window is",
            "   not focused. */",
            f"@define-color {'placeholder_text_color':<26}#{p['muted']};",
            "treeview.view.cell.chromium:selected:focus { background-color: @accent_bg_color; color: @accent_fg_color; }",
            "tooltip.background.chromium { background-color: @popover_bg_color; border-color: @headerbar_border_color; }",
            "tooltip.chromium * { color: @popover_fg_color; text-shadow: none; }",
            "headerbar.chromium:backdrop { background-color: @headerbar_bg_color; }"]
    return "\n".join(out) + "\n"


