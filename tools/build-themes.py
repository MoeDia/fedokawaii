def check_copies():
    known = {v for p in P.values() for v in p.values() if isinstance(v, str) and re.fullmatch(r"[0-9a-f]{6}", v)}
    known |= {c for p in P.values() for c in ansi(p)} | set(EDITOR.values())
    bad = []
    for rel in COPIES:
        text = (ROOT / rel).read_text()
        for n, line in enumerate(text.splitlines(), 1):
            found = re.findall(r"(?:#|0x)([0-9a-fA-F]{6})(?:[0-9a-fA-F]{2})?(?![0-9A-Za-z])", line)
            # bare ones (key=c0ffee, lists a,b,c): only with a digit in them, so no word is taken for
            # one — and after a space only with a letter too, so no number is ((t < 500000), sleeps)
            found += [h for h in re.findall(r"(?<=[=,'\"])([0-9a-fA-F]{6})(?![0-9A-Za-z])", line)
                      if re.search(r"[0-9]", h)]
            found += [h for h in re.findall(r"(?<=\s)([0-9a-fA-F]{6})(?![0-9A-Za-z])", line)
                      if re.search(r"[0-9]", h) and re.search(r"[a-fA-F]", h)]
            for h in found:
                if h.lower() not in known:
                    bad.append(f"{rel}:{n}: {h} is not a palette colour")
    if bad:
        raise SystemExit("colours outside the palettes:\n  " + "\n  ".join(bad))


def panel_conf(m, p):
    """kawa-panel, quick settings: it draws itself (every square and segment on the pixel grid),
    so it takes the colours by name rather than as CSS — and its frame's, as the bar's tiles have
    it (KAMI: the hairline and the shadow's two rows, each with its own opacity: rrggbbaa)."""
    keys = ("ground", "key", "edge", "edge2", "faint", "muted", "text", "strong", "accent",
            "accent_text", "accent_lo", "text_on_accent", "asagi", "flame")
    k = KAMI[m]
    frame = {"hair": k["hair"], "shadow1": k["shadow"][0], "shadow2": k["shadow"][1]}
    return (f"# {header('~/.config/fedokawaii/current/panel.conf', 'quick settings in ' + NAMES[m])}\n"
            + "".join(f"{k}={p[k]}\n" for k in keys)
            + "".join(f"{n}={''.join(f'{c:02x}' for c in v)}\n" for n, v in frame.items()))


def saver_conf(m, p):
    """kawa-saver, the screensaver: it draws dot by dot (C), so it takes the colours by name —
    the ground, the sashiko's thread and its shadow (muted and lo on the ink, blue and edge on
    the paper), the seals' vermilion, its clock's panel."""
    dark = m == "dark"
    c = dict(p, thread=p["muted"] if dark else p["blue"], shade=p["lo"] if dark else p["edge"])
    keys = ("ground", "surface", "edge2", "thread", "shade", "text", "accent", "accent_text")
    return (f"# {header('~/.config/fedokawaii/current/saver.conf', 'the screensaver in ' + NAMES[m])}\n"
            + "".join(f"{k}={c[k]}\n" for k in keys))


