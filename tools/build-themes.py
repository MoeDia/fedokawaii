"""tools/build-themes.py — write every colour file of the two themes from one palette.

    python3 tools/build-themes.py
    python3 tools/build-themes.py --palette FILE --out DIR   a trial: FILE (python) redefines P,
        KAMI, TILE, EDITOR …; every file written under DIR instead (as configs/home lays them out:
        DIR/.config/fedokawaii/themes/…, DIR/.config/foot/foot.ini …) for tools/kit.sh --themes DIR;
        the repo untouched, the copies' check skipped (their colours are today's)

The desktop has two themes: "dark" (sumi ink: ink-black ground, unbleached-paper text)
and "light" (washi paper: warm paper ground, ink text). Both share the accents
(vermilion, matcha, yamabuki, indigo, wisteria, asagi), deepened on paper so they keep
their contrast. This script is the only place the colours are written down; it renders:

  configs/home/.config/fedokawaii/themes/<mode>/   one folder per theme, read through
      colors.sh  waybar.css  foot.ini            the ~/.config/fedokawaii/current
      mako  qt6ct.conf  qt6ct-colors.conf          link that kawa-theme switches
      btop.theme  zathurarc  imv  gtklock.css  mpv.conf  wiremix.toml
      dwl.colors  panel.conf  saver.conf
      kami-{tile,red,fibre,seal,scroll}.png        (the bar's washi tiles: 紙 kami)
  configs/home/.config/foot/foot.ini              the [colors-dark] / [colors-light] block
  configs/home/.config/gtk-4.0/gtk.css            both themes, chosen by GTK's media query
  configs/home/.local/share/themes/Fedokawaii{,-dark}/   the two GTK 3 themes
  configs/home/.config/nvim/lua/plugins/colorscheme.lua   gruvbox remapped to both palettes

A few files cannot include a generated one (dwl's config.h is compiled in; mpv's subtitles,
satty, MangoHud, fetch and the scripts' fallbacks hold literal colours): each run checks that
every colour written in them is one of the palettes' (COPIES below), and stops if not.

Outputs are committed, so installing needs no Python. Run again after changing a colour.
"""
