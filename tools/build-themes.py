def foot_block():
    out = ["# >>> colours: generated by tools/build-themes.py — edit the palette there",
           "# Both palettes live here; foot starts in the one named by the include above and",
           "# kawa-theme switches every open window (SIGUSR1 = dark, SIGUSR2 = light)."]
    for m in ("dark", "light"):
        p = P[m]
        a = ansi(p)
        out += ["", f"[colors-{m}]", f"# {NAMES[m]}",
                f"foreground={p['text']}", f"background={p['ground']}",
                f"cursor={p['ground']} {p['accent']}",
                f"selection-foreground={p['ground']}", f"selection-background={p['ansi7']}",
                f"urls={p['bblue']}", f"jump-labels={p['ground']} {p['yellow']}",
                f"scrollback-indicator={p['ground']} {p['ansi7']}",
                f"search-box-no-match={p['strong'] if m == 'dark' else p['hi']} {p['red']}",
                f"search-box-match={p['ground']} {p['ansi7']}"]
        out += [f"regular{i}={a[i]}" for i in range(8)]
        out += [f"bright{i}={a[8 + i]}" for i in range(8)]
        # the desktop's own three, past the sixteen, for every list in a terminal (fzf.opts,
        # VisiData): 16 the fill of what is selected (vermilion), 17 the words on it, 18 the
        # soft fill under the pointer — switched with the theme like the rest
        out += [f"16={p['accent']}", f"17={p['text_on_accent']}", f"18={p['edge']}"]
    out.append("# <<< colours")
    return "\n".join(out)


